"""Bake the bundled Natural Earth boundary into an indexed, concave terrain mesh.

Run from any directory with Python 3. No network or third-party packages needed.
"""
import json
import math
from pathlib import Path

root = Path(__file__).resolve().parents[1]
source = json.loads((root / 'assets/maps/kazakhstan.geojson').read_text())
ring = source['geometry']['coordinates'][0][:-1]
# Equirectangular projection at 48 N, with Baikonur's launch area at the origin.
# Compress the country to 10,000 scene units wide, retaining its aspect ratio.
longitude_scale = math.cos(math.radians(48))
scale = 10000 / ((max(p[0] for p in ring) - min(p[0] for p in ring)) * longitude_scale)
points = [((lon - 63.34) * longitude_scale * scale, (lat - 45.92) * scale)
          for lon, lat in ring]


def cross(a, b, c):
    return (b[0] - a[0]) * (c[1] - a[1]) - (b[1] - a[1]) * (c[0] - a[0])


if sum(a[0] * b[1] - b[0] * a[1] for a, b in zip(points, points[1:] + points[:1])) < 0:
    points.reverse()
# Ear clipping preserves indentations, unlike a fan from the country's centre.
remaining = list(range(len(points)))
triangles = []
while len(remaining) > 3:
    for i, b in enumerate(remaining):
        a, c = remaining[i - 1], remaining[(i + 1) % len(remaining)]
        if cross(points[a], points[b], points[c]) <= 1e-7:
            continue
        if any(min(cross(points[a], points[b], points[p]),
                   cross(points[b], points[c], points[p]),
                   cross(points[c], points[a], points[p])) >= -1e-7
               for p in remaining if p not in (a, b, c)):
            continue
        triangles.append((a, b, c))
        del remaining[i]
        break
    else:
        raise ValueError('Boundary could not be triangulated')
triangles.append(tuple(remaining))

header = ['// Generated by tools/generate_kazakhstan.py; do not edit by hand.',
          '// Natural Earth v5.1.2 public-domain boundary; see CREDITS.md.',
          '#pragma once', '#include <glm/glm.hpp>', 'namespace bk {',
          '// East is +X; north is -Z. Baikonur is (0, 0).',
          'inline const glm::vec2 kazakhstanBoundary[] = {']
header += [f'    {{{x:.4f}f, {-north:.4f}f}},' for x, north in points]
header += ['};', 'inline constexpr unsigned kazakhstanTriangles[] = {']
header += [f'    {a}, {b}, {c},' for a, b, c in triangles]
header += ['};', '} // namespace bk', '']
(root / 'src/KazakhstanBoundary.hpp').write_text('\n'.join(header))
print(f'Baked {len(points)} boundary points and {len(triangles)} top triangles')
