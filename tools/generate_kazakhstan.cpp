// Bake the bundled single-ring Natural Earth polygon using C++17 only.
#include <algorithm>
#include <cmath>
#include <cstdlib>
#include <fstream>
#include <iomanip>
#include <iostream>
#include <iterator>
#include <numeric>
#include <stdexcept>
#include <string>
#include <vector>
struct Point { double x, y; };
static double cross(Point a, Point b, Point c) {
    return (b.x-a.x)*(c.y-a.y)-(b.y-a.y)*(c.x-a.x);
}
int main(int argc, char** argv) {
    try {
        if (argc != 3) throw std::runtime_error("Usage: generate_kazakhstan input.geojson output.hpp");
        std::ifstream input(argv[1]);
        if (!input) throw std::runtime_error("Cannot open map input");
        std::string json((std::istreambuf_iterator<char>(input)), {});
        auto start = json.find("\"coordinates\"");
        if (start == std::string::npos) throw std::runtime_error("Missing coordinates");
        start = json.find('[', start);
        if (start == std::string::npos) throw std::runtime_error("Missing coordinate array");
        // The bundled GeoJSON has one polygon ring, with two numbers per vertex.
        std::vector<double> values;
        int depth = 0;
        std::size_t rings = 0;
        const char* cursor = json.c_str()+start;
        do {
            const char c = *cursor;
            if (!c) throw std::runtime_error("Unterminated coordinates");
            if (c == '[') { ++depth; if (depth == 2) ++rings; }
            else if (c == ']') --depth;
            else if ((c >= '0' && c <= '9') || c == '-') {
                char* end = nullptr;
                const double value = std::strtod(cursor, &end);
                if (depth != 3 || end == cursor || !std::isfinite(value))
                    throw std::runtime_error("Invalid coordinate");
                values.push_back(value); cursor = end; continue;
            } else if (c != ',' && c != ' ' && c != '\n' && c != '\r' && c != '\t') {
                throw std::runtime_error("Unexpected coordinate data");
            }
            ++cursor;
        } while (depth > 0);
        if (rings != 1 || values.size() < 8 || values.size()%2 != 0)
            throw std::runtime_error("Expected a single closed polygon ring");
        std::vector<Point> points;
        for (std::size_t i=0; i<values.size(); i+=2) points.push_back({values[i],values[i+1]});
        if (points.front().x != points.back().x || points.front().y != points.back().y)
            throw std::runtime_error("Polygon ring is not closed");
        points.pop_back();
        const auto bounds = std::minmax_element(points.begin(),points.end(),[](Point a,Point b){return a.x<b.x;});
        const double longitudeScale = std::cos(48.0*std::acos(-1.0)/180.0);
        const double width = bounds.second->x-bounds.first->x;
        if (width <= 0) throw std::runtime_error("Degenerate polygon");
        const double scale = 10000.0/(width*longitudeScale);
        for (auto& p : points) p = {(p.x-63.34)*longitudeScale*scale,(p.y-45.92)*scale};
        double area = 0;
        for (std::size_t i=0; i<points.size(); ++i) {
            const auto a=points[i], b=points[(i+1)%points.size()]; area += a.x*b.y-b.x*a.y;
        }
        if (area < 0) std::reverse(points.begin(),points.end());
        std::vector<unsigned> remaining(points.size()), triangles;
        std::iota(remaining.begin(),remaining.end(),0);
        while (remaining.size()>3) {
            bool found=false;
            for (std::size_t i=0; i<remaining.size(); ++i) {
                const auto a=remaining[(i+remaining.size()-1)%remaining.size()], b=remaining[i], c=remaining[(i+1)%remaining.size()];
                if (cross(points[a],points[b],points[c])<=1e-7) continue;
                bool contains=false;
                for (auto p : remaining) {
                    if (p==a || p==b || p==c) continue;
                    if (std::min({cross(points[a],points[b],points[p]),cross(points[b],points[c],points[p]),cross(points[c],points[a],points[p])})>=-1e-7) { contains=true; break; }
                }
                if (contains) continue;
                triangles.insert(triangles.end(),{a,b,c});
                remaining.erase(remaining.begin()+static_cast<std::ptrdiff_t>(i)); found=true; break;
            }
            if (!found) throw std::runtime_error("Boundary could not be triangulated");
        }
        triangles.insert(triangles.end(),remaining.begin(),remaining.end());
        std::ofstream out(argv[2]);
        if (!out) throw std::runtime_error("Cannot open output header");
        out << "// Generated by tools/generate_kazakhstan.cpp; do not edit by hand.\n"
            "// Natural Earth v5.1.2 public-domain boundary; see CREDITS.md.\n"
            "#pragma once\n#include <glm/glm.hpp>\nnamespace bk {\n"
            "// East is +X; north is -Z. Baikonur is (0, 0).\n"
            "inline const glm::vec2 kazakhstanBoundary[] = {\n" << std::fixed << std::setprecision(4);
        for (auto p : points) out << "    {" << p.x << "f, " << -p.y << "f},\n";
        out << "};\ninline constexpr unsigned kazakhstanTriangles[] = {\n";
        for (std::size_t i=0; i<triangles.size(); i+=3)
            out << "    " << triangles[i] << ", " << triangles[i+1] << ", " << triangles[i+2] << ",\n";
        out << "};\n} // namespace bk\n";
        out.close();
        if (!out) throw std::runtime_error("Failed writing header");
        std::cout << "Baked " << points.size() << " boundary points and " << triangles.size()/3 << " top triangles\n";
    } catch (const std::exception& error) { std::cerr << error.what() << '\n'; return 1; }
}
