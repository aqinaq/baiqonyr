// Bake the bundled Natural Earth polygon; no network or external packages.
import fs from 'node:fs';
import path from 'node:path';
import {root} from './common.mjs';
const ring=JSON.parse(fs.readFileSync(path.join(root,'assets/maps/kazakhstan.geojson'),'utf8')).geometry.coordinates[0].slice(0,-1);
const longitudeScale=Math.cos(48*Math.PI/180);
const scale=10000/((Math.max(...ring.map(p=>p[0]))-Math.min(...ring.map(p=>p[0])))*longitudeScale);
const points=ring.map(([lon,lat])=>[(lon-63.34)*longitudeScale*scale,(lat-45.92)*scale]);
const cross=(a,b,c)=>(b[0]-a[0])*(c[1]-a[1])-(b[1]-a[1])*(c[0]-a[0]);
if(points.reduce((sum,a,i)=>{const b=points[(i+1)%points.length];return sum+a[0]*b[1]-b[0]*a[1];},0)<0)points.reverse();
const remaining=points.map((_,i)=>i), triangles=[];
while(remaining.length>3){
  let found=false;
  for(let i=0;i<remaining.length;i++){
    const a=remaining[(i+remaining.length-1)%remaining.length], b=remaining[i], c=remaining[(i+1)%remaining.length];
    if(cross(points[a],points[b],points[c])<=1e-7)continue;
    if(remaining.some(p=>p!==a&&p!==b&&p!==c&&Math.min(cross(points[a],points[b],points[p]),cross(points[b],points[c],points[p]),cross(points[c],points[a],points[p]))>=-1e-7))continue;
    triangles.push([a,b,c]);remaining.splice(i,1);found=true;break;
  }
  if(!found)throw Error('Boundary could not be triangulated');
}
triangles.push(remaining);
const header=['// Generated by tools/generate_kazakhstan.mjs; do not edit by hand.',
'// Natural Earth v5.1.2 public-domain boundary; see CREDITS.md.','#pragma once','#include <glm/glm.hpp>','namespace bk {',
'// East is +X; north is -Z. Baikonur is (0, 0).','inline const glm::vec2 kazakhstanBoundary[] = {',
...points.map(([x,n])=>`    {${x.toFixed(4)}f, ${(-n).toFixed(4)}f},`),'};','inline constexpr unsigned kazakhstanTriangles[] = {',
...triangles.map(t=>`    ${t.join(', ')},`),'};','} // namespace bk',''];
fs.writeFileSync(path.join(root,'src/KazakhstanBoundary.hpp'),header.join('\n'));
console.log(`Baked ${points.length} boundary points and ${triangles.length} top triangles`);
